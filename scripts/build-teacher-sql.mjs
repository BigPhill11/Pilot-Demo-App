#!/usr/bin/env node
// Bundles the teacher-feature migrations into two files that can be pasted into
// the Supabase dashboard SQL editor, for projects whose migration history was
// never tracked by the CLI.
//
// The split is not cosmetic. The editor runs a tab in one transaction, and
// Postgres refuses to use an enum value in the transaction that added it, so
// the enum migration has to be its own paste.
//
// Regenerate after touching any migration listed below:
//   node scripts/build-teacher-sql.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrations = join(root, 'supabase', 'migrations');
const outDir = join(root, 'docs', 'sql');

const ENUM_FILE = '20260801000000_teacher_role_enum.sql';

const REST_FILES = [
  '20260801000100_classrooms.sql',
  '20260801000200_teacher_rpcs.sql',
  '20260801000300_sync_module_progress.sql',
  '20260801000400_teacher_signup.sql',
  '20260802000000_access_code_lifecycle.sql',
  '20260802000100_teacher_role_grant.sql',
  '20260802000200_assessment_responses.sql',
  '20260802000300_teacher_teachback.sql',
];

const banner = (title, body) =>
  [
    '-- ============================================================',
    `-- ${title}`,
    '--',
    ...body.map((line) => `-- ${line}`.trimEnd()),
    '--',
    '-- Generated by scripts/build-teacher-sql.mjs — do not edit by hand.',
    '-- Edit the files in supabase/migrations and regenerate.',
    '-- ============================================================',
    '',
    '',
  ].join('\n');

const read = (file) => readFileSync(join(migrations, file), 'utf8').replace(/\s*$/, '\n');

const separator = (file) =>
  [
    '',
    '',
    '-- ------------------------------------------------------------',
    `-- ${file}`,
    '-- ------------------------------------------------------------',
    '',
  ].join('\n');

mkdirSync(outDir, { recursive: true });

const partOne =
  banner('TEACHER SETUP — PART 1 OF 2', [
    'Paste this whole file into the Supabase SQL editor and run it.',
    'It adds one value to an enum and finishes in well under a second.',
    '',
    'Then open a NEW query tab and run part 2. Running them in the same',
    'tab fails, because part 2 uses the enum value part 1 creates.',
    '',
    `Source: supabase/migrations/${ENUM_FILE}`,
  ]) + read(ENUM_FILE);

const partTwo =
  banner('TEACHER SETUP — PART 2 OF 2', [
    'Run part 1 first, in its own query tab.',
    '',
    'Paste this whole file into a new Supabase SQL editor tab and run it.',
    'It creates the classroom tables, the dashboard functions, answer',
    'capture, and the access-code limits. It is safe to re-run: every',
    'statement is guarded with IF NOT EXISTS or CREATE OR REPLACE.',
    '',
    `Source: ${REST_FILES.length} files from supabase/migrations, concatenated`,
    'in filename order.',
  ]) +
  REST_FILES.map((file, index) => (index === 0 ? '' : separator(file)) + read(file)).join('');

writeFileSync(join(outDir, 'teacher-setup-part-1-enum.sql'), partOne);
writeFileSync(join(outDir, 'teacher-setup-part-2-feature.sql'), partTwo);

const lines = (text) => text.split('\n').length;
console.log(`part 1: ${lines(partOne)} lines (1 migration)`);
console.log(`part 2: ${lines(partTwo)} lines (${REST_FILES.length} migrations)`);
